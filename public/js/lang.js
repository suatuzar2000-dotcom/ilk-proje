let currentLang = localStorage.getItem('oturum_lang') || 'tr';

function t(str) {
  if (currentLang === 'tr') return str;
  if (translations[currentLang] && translations[currentLang][str]) return translations[currentLang][str];
  return str;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('oturum_lang', lang);

  if (lang === 'ar') {
    document.documentElement.dir = 'rtl';
    document.body.classList.add('rtl-lang');
  } else {
    document.documentElement.dir = 'ltr';
    document.body.classList.remove('rtl-lang');
  }

  translateDOM(document.body, translations[lang]);

  if (typeof buildSummary === 'function' && document.getElementById('statGrid')) {
    buildSummary();
  }
}

function translateDOM(node, langDict) {
  if (node.nodeType === 3) {
    if (typeof node.originalText === 'undefined') {
      node.originalText = node.nodeValue;
    }
    const origTrimmed = node.originalText.trim();
    if (origTrimmed.length > 0) {
      if (langDict && langDict[origTrimmed]) {
        node.nodeValue = node.originalText.replace(origTrimmed, langDict[origTrimmed]);
      } else {
        node.nodeValue = node.originalText;
      }
    }
  } else if (node.nodeType === 1) {
    if (node.tagName === 'SCRIPT' || node.tagName === 'STYLE' || node.tagName === 'LINK') return;

    if (node.tagName === 'INPUT' && node.hasAttribute('data-tr-name')) return;

    if (node.hasAttribute('placeholder')) {
      if (!node.hasAttribute('data-orig-placeholder')) {
        node.setAttribute('data-orig-placeholder', node.getAttribute('placeholder'));
      }
      const origPlace = node.getAttribute('data-orig-placeholder');
      if (langDict && langDict[origPlace]) node.setAttribute('placeholder', langDict[origPlace]);
      else node.setAttribute('placeholder', origPlace);
    }

    if (node.tagName === 'INPUT' && (node.type === 'button' || node.type === 'submit')) {
      if (!node.hasAttribute('data-orig-value')) node.setAttribute('data-orig-value', node.value);
      const origVal = node.getAttribute('data-orig-value');
      if (langDict && langDict[origVal]) node.value = langDict[origVal];
      else node.value = origVal;
    }

    for (let i = 0; i < node.childNodes.length; i++) {
      translateDOM(node.childNodes[i], langDict);
    }
  }
}

document.addEventListener('DOMContentLoaded', () => {
  setLanguage(currentLang);
  const switcher = document.getElementById('langSwitcher');
  if (switcher) switcher.value = currentLang;
});
